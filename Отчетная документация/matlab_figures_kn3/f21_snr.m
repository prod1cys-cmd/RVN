ylim([50 105]); xlim([0 500]);
xlabel('Частота сигнала, МГц'); ylabel('ОСШ, дБпш');
legend({'рабочая полоса 50–70 МГц','К5119ПВ1Я, типовое','К5119ПВ1Я, минимальное','предел по джиттеру 330 фс','предел по джиттеру 100 фс','предел квантования 14 бит'},'Location','northeast');
fig_save(h,'f21_snr');
