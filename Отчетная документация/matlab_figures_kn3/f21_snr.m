% Рисунок: ОСШ тракта оцифровки и ограничивающие факторы
fa  = [10 54 120 195 245 365 490];      % МГц, точки паспортных зависимостей К5119ПВ1Я [17]
qty = [65 65 64 63 62 61 60];           % типовое ОСШ, дБпш
qmn = [62 62 61 61 60 59 58];           % минимальное ОСШ, дБпш
f = linspace(10,500,400)*1e6;
